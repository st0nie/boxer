use crate::Colors;
use crate::args::Args;
use crate::debian::{BuildArtifacts, collect_files, get_binary_packages, get_source_info};
use crate::deps::run_deps;
use crate::exec::run;
use crate::fmt::{detail, info, success};

use anyhow::{Context, Result, bail};
use std::fs;
use std::path::Path;
use std::process::Command;

pub fn run_build(c: &Colors, args: &Args) -> Result<()> {
    let _root = crate::exec::acquire_root()?;
    crate::tools::ensure_installed(
        c,
        args,
        &[
            "quilt",
            "dpkg-parsechangelog",
            "mk-build-deps",
            "dpkg-buildpackage",
        ],
    )?;
    info(c, "starting build pipeline");

    crate::check::run_check(c, args)?;
    run_deps(c, args, None)?;

    let (source, version) = get_source_info()?;
    success(c, &format!("building {} {}", source, version));

    info(c, "running dpkg-buildpackage");
    let mut cmd = Command::new("dpkg-buildpackage");
    cmd.args(["-b", "-uc", "-us"])
        .env("DEB_BUILD_OPTIONS", "nocheck");
    run(&mut cmd)?;
    success(c, "dpkg-buildpackage finished");

    let current = std::env::current_dir()?;
    let parent = Path::new("..").canonicalize()?;

    // Read debian/control after the build so a control file generated by the
    // build is already in place.
    let artifacts = BuildArtifacts::new(&source, &version, &get_binary_packages()?);

    info(c, "collecting generated debs");
    let debs = collect_files(&parent, |name| artifacts.is_current_binary(name))?;
    if debs.is_empty() {
        bail!("no .deb files were generated for {} {}", source, version);
    }

    let mut local_names = Vec::with_capacity(debs.len());
    for src in &debs {
        let name = src
            .file_name()
            .with_context(|| format!("artifact has no file name: {:?}", src))?
            .to_os_string();
        let dst = current.join(&name);
        move_file(src, &dst).with_context(|| format!("failed to move {:?} to {:?}", src, dst))?;
        success(c, &format!("moved {}", dst.display()));
        local_names.push(name);
    }

    let tarball = format!("{}-{}.tar.gz", source, version);
    info(c, &format!("creating tarball: {}", tarball));

    let mut cmd = Command::new("tar");
    cmd.args(["--force-local", "-czf"])
        .arg(&tarball)
        .args(&local_names);
    run(&mut cmd)?;
    success(c, &format!("created {}", tarball));

    info(c, "cleaning generated files");
    for name in &local_names {
        fs::remove_file(Path::new(name)).context("failed to remove local deb")?;
    }
    clean_parent_build_artifacts(c, &artifacts)?;

    success(c, &format!("build complete: {}", tarball));
    Ok(())
}

/// Move a file, falling back to copy+remove when source and destination live
/// on different filesystems (`rename` fails with `EXDEV` in that case).
fn move_file(src: &Path, dst: &Path) -> Result<()> {
    match fs::rename(src, dst) {
        Ok(()) => Ok(()),
        Err(e) if e.kind() == std::io::ErrorKind::CrossesDevices => {
            fs::copy(src, dst).with_context(|| format!("failed to copy {:?} to {:?}", src, dst))?;
            fs::remove_file(src).with_context(|| format!("failed to remove {:?}", src))?;
            Ok(())
        }
        Err(e) => Err(anyhow::Error::new(e)),
    }
}

/// Remove this source package's generated artifacts (any version) from the
/// parent directory. Files belonging to other packages are left alone, which
/// matters when the parent directory is a shared workspace.
fn clean_parent_build_artifacts(c: &Colors, artifacts: &BuildArtifacts) -> Result<()> {
    let parent = Path::new("..").canonicalize()?;
    for path in collect_files(&parent, |name| artifacts.is_source_artifact(name))? {
        detail(c, &format!("removing {}", path.display()));
        fs::remove_file(&path).with_context(|| format!("failed to remove {:?}", path))?;
    }
    Ok(())
}
